"""Step 3. Run every showcase query in sql/, time it, write data/*.json and RESULTS.md.

Each .sql file is run statement by statement on one connection. A statement that MariaDB refuses is
reported with its error (two of the demos are refusals on purpose). The last SELECT of a file is run
seven times and the median wall time is reported.

    uv run report.py
"""
import datetime, decimal, json, statistics, time
from pathlib import Path
import pymysql

ROOT = Path(__file__).resolve().parent
SQL, DATA = ROOT / "sql", ROOT / "data"
DB = "lab_bitemporal_offices"
FILES = ["a-who-held-office", "a2-answer-that-flips", "a3-nobody", "b-list-as-of", "b2-list-as-of-long", "b3-terms-now",
         "c-term-changes", "c2-change-summary", "c3-short-lived", "d-gaps-and-overlaps", "d2-gaps-by-year", "d3-two-at-once", "e-for-portion-of",
         "e2-portion-history", "f-office-holder-function", "f2-office-holder-calls", "g-lifetimes"]
JSON_OUT = {  # file -> (json name, title, unit)
    "b3-terms-now": ("terms-now.json", "Terms of office Finnish Wikipedia states today, from the infoboxes of the 13 presidents' articles",
                     "one stated term; valid_to is exclusive and null while in office"),
    "b2-list-as-of-long": ("terms-by-asof.json", "The presidents of Finland and their terms as Wikipedia stated them at the end of 2006, 2012, 2020 and now",
                           "one stated term per president per as-of date"),
    "c-term-changes": ("term-changes.json", "Every time Wikipedia replaced a stated start or end of a term with another",
                       "one change; new_value_stood_days is null while the new value is still stated"),
    "d2-gaps-by-year": ("gaps-by-asof.json", "Handovers between presidents that do not meet, as Wikipedia stood at each year end",
                        "counts and days per year end (2026 = now)"),
    "d3-two-at-once": ("two-at-once.json", "Moments when two articles claimed the presidency for the same days",
                       "one pair of statements live at the same time"),
}

def plain(v):
    if isinstance(v, decimal.Decimal):
        return int(v) if v == v.to_integral_value() else float(v)
    if isinstance(v, (datetime.datetime, datetime.date)):
        return str(v)
    return v

def md_table(cols, rows, width=70):
    def cell(v):
        s = "" if v is None else str(v).replace("\n", " ").replace("|", "\\|")
        return s if len(s) <= width else s[:width - 1] + "…"
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return "\n".join(out)

def statements(text):
    body = "\n".join(l for l in text.splitlines() if not l.strip().startswith("--"))
    return [s.strip() for s in body.split(";\n") if s.strip().rstrip(";")]

def main():
    c = pymysql.connect(host="127.0.0.1", port=3310, user="root", password="wtt", database=DB, autocommit=True)
    cur = c.cursor()
    cur.execute("SET time_zone = '+00:00'")
    md, timings = ["# Results\n", "Generated by `uv run report.py`. Do not edit by hand.\n"], []
    for name in FILES:
        text = (SQL / f"{name}.sql").read_text()
        stmts = statements(text)
        md.append(f"\n## {name}.sql\n")
        last = None
        for i, stmt in enumerate(stmts):
            stmt = stmt.rstrip(";")
            t0 = time.perf_counter()
            try:
                cur.execute(stmt)
            except pymysql.err.MySQLError as e:
                md.append(f"Statement {i + 1} refused: `ERROR {e.args[0]}: {e.args[1]}`\n")
                timings.append({"query": name, "statement": i + 1, "ms": round((time.perf_counter() - t0) * 1000, 2),
                                "rows": None, "refused": f"{e.args[0]}: {e.args[1]}"})
                continue
            ms = (time.perf_counter() - t0) * 1000
            if cur.description:
                cols = [d[0] for d in cur.description]
                rows = [[plain(v) for v in r] for r in cur.fetchall()]
                last = (i, stmt, cols, rows)
            else:
                md.append(f"Statement {i + 1}: {cur.rowcount} rows affected, {ms:.1f} ms\n")
                timings.append({"query": name, "statement": i + 1, "ms": round(ms, 2), "rows": cur.rowcount})
        if last:
            i, stmt, cols, rows = last
            runs = []
            is_select = stmt.lstrip().upper().startswith(("SELECT", "WITH")) and " INTO @" not in stmt
            for _ in range(7 if is_select else 0):
                t0 = time.perf_counter(); cur.execute(stmt); cur.fetchall(); runs.append((time.perf_counter() - t0) * 1000)
            ms = statistics.median(runs) if runs else None
            timings.append({"query": name, "statement": i + 1, "ms": None if ms is None else round(ms, 2), "rows": len(rows)})
            md.append(md_table(cols, rows, 110 if name.startswith("f2") else 70))
            md.append(f"\n{len(rows)} rows, median of 7 runs: {ms:.1f} ms\n" if ms is not None else f"\n{len(rows)} rows\n")
            if name in JSON_OUT:
                fname, title, unit = JSON_OUT[name]
                (DATA / fname).write_text(json.dumps({
                    "title": title, "unit": unit,
                    "source": f"lab_bitemporal_offices.office_term; sql/{name}.sql",
                    "rows": [dict(zip(cols, r)) for r in rows]}, ensure_ascii=False, indent=2) + "\n")

    # -- one holder per day across all articles: what UNIQUE (office, valid_time WITHOUT OVERLAPS) refuses, moment by moment
    cur.execute("SELECT DISTINCT TIMESTAMPADD(SECOND, 1, GREATEST(a.row_start, b.row_start)) "
                "FROM office_term FOR SYSTEM_TIME ALL a JOIN office_term FOR SYSTEM_TIME ALL b "
                "ON b.office = a.office AND b.page_id <> a.page_id AND a.valid_from < b.valid_to AND b.valid_from < a.valid_to "
                "AND a.row_start < b.row_end AND b.row_start < a.row_end "
                "AND TIMESTAMPDIFF(SECOND, GREATEST(a.row_start, b.row_start), LEAST(a.row_end, b.row_end)) > 1 "
                "WHERE a.office = 'Suomen tasavallan presidentti'")
    moments = [(str(r[0]), "moment found by d3") for r in cur.fetchall()]
    moments += [(f"{y}-12-31 23:59:59", "year end") for y in range(2006, 2026)]
    cur.execute("SELECT NOW(6)"); moments.append((str(cur.fetchone()[0]), "now"))
    trial = []
    for moment, why in sorted(moments):
        cur.execute("CREATE OR REPLACE TABLE one_holder_probe (office VARCHAR(64) NOT NULL, person VARCHAR(255) NOT NULL, "
                    "valid_from DATE NOT NULL, valid_to DATE NOT NULL, PERIOD FOR valid_time (valid_from, valid_to), "
                    "UNIQUE (office, valid_time WITHOUT OVERLAPS))")
        cur.execute("SELECT office, person, valid_from, valid_to FROM office_term FOR SYSTEM_TIME AS OF %s "
                    "WHERE office = 'Suomen tasavallan presidentti' ORDER BY valid_from, valid_to", (moment,))
        offered, refused = cur.fetchall(), []
        for row in offered:
            try:
                cur.execute("INSERT INTO one_holder_probe VALUES (%s,%s,%s,%s)", row)
            except pymysql.err.IntegrityError:
                refused.append(f"{row[1]} {row[2]}..{row[3]}")
        trial.append({"wikipedia_as_of": moment, "why_this_moment": why, "terms_offered": len(offered),
                      "refused": len(refused), "refused_terms": "; ".join(refused)})
    cur.execute("DROP TABLE one_holder_probe")
    (DATA / "one-holder-trial.json").write_text(json.dumps({
        "title": "What UNIQUE (office, valid_time WITHOUT OVERLAPS) refuses when the presidents' stated terms as of one moment are inserted in order",
        "unit": "terms offered and refused per moment of Wikipedia's history",
        "source": "report.py, scratch table one_holder_probe filled from office_term FOR SYSTEM_TIME AS OF each moment",
        "rows": trial}, ensure_ascii=False, indent=2) + "\n")
    md.append("\n## One holder per day across articles: `UNIQUE (office, valid_time WITHOUT OVERLAPS)`\n")
    md.append(md_table(list(trial[0]), [list(t.values()) for t in trial], 90))
    md.append(f"\n{sum(t['refused'] > 0 for t in trial)} of {len(trial)} moments have a refused term; "
              f"{sum(t['refused'] > 0 for t in trial if t['why_this_moment'] != 'moment found by d3')} of the "
              f"{sum(t['why_this_moment'] != 'moment found by d3' for t in trial)} year ends and now.\n")

    (DATA / "query-timings.json").write_text(json.dumps({
        "title": "Wall time of each showcase statement", "unit": "milliseconds (median of 7 runs for SELECTs, single run for DDL and DML)",
        "source": "report.py over sql/*.sql on lab_bitemporal_offices, MariaDB 12.3.3", "rows": timings},
        ensure_ascii=False, indent=2) + "\n")
    md.append("\n## Timings\n")
    md.append(md_table(["query", "statement", "ms", "rows", "refused"],
                       [[t["query"], t["statement"], t["ms"], t["rows"], t.get("refused", "")] for t in timings]))
    (ROOT / "RESULTS.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))

if __name__ == "__main__":
    main()
